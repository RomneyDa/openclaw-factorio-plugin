#!/usr/bin/env node
import net from 'node:net';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { readFile } from 'node:fs/promises';

const DEFAULT_CREDENTIAL_FILE = join(homedir(), '.openclaw', 'factorio-runtime-rcon.json');
const SERVERDATA_AUTH = 3;
const SERVERDATA_EXECCOMMAND = 2;

function usage() {
  console.log(`Factorio OpenClaw RCON bridge

Usage:
  factorio-rcon <command> [args]

Connection sources, in precedence order:
  env FACTORIO_RCON_HOST / FACTORIO_RCON_PORT / FACTORIO_RCON_PASSWORD
  ~/.openclaw/factorio-runtime-rcon.json generated by: openclaw factorio setup
  defaults: 127.0.0.1:27015

Commands:
  raw <factorio-command>              Send a raw Factorio command over RCON
  call <api> [args...]                Call remote.call("openclaw", api, ...args)
  state [player]                      Get player/game state
  inventory [player]                  Get inventory
  nearby [player] [radius]            Get nearby entities
  production [player]                 Get production stats
  chat <message>                      Print OpenClaw chat message
`);
}

async function loadConfig() {
  let file = {};
  try { file = JSON.parse(await readFile(process.env.FACTORIO_RCON_CREDENTIAL_FILE || DEFAULT_CREDENTIAL_FILE, 'utf8')); } catch {}
  return {
    host: process.env.FACTORIO_RCON_HOST || file.host || '127.0.0.1',
    port: Number(process.env.FACTORIO_RCON_PORT || file.port || 27015),
    password: process.env.FACTORIO_RCON_PASSWORD || file.password || '',
  };
}

function encodePacket(id, type, body) {
  const bodyBuf = Buffer.from(String(body ?? ''), 'utf8');
  const size = 4 + 4 + bodyBuf.length + 2;
  const buf = Buffer.alloc(4 + size);
  buf.writeInt32LE(size, 0);
  buf.writeInt32LE(id, 4);
  buf.writeInt32LE(type, 8);
  bodyBuf.copy(buf, 12);
  buf.writeInt16LE(0, 12 + bodyBuf.length);
  return buf;
}

function decodePackets(buffer) {
  const packets = [];
  let offset = 0;
  while (buffer.length - offset >= 4) {
    const size = buffer.readInt32LE(offset);
    if (size < 10) throw new Error(`Invalid RCON packet size: ${size}`);
    if (buffer.length - offset < 4 + size) break;
    packets.push({
      id: buffer.readInt32LE(offset + 4),
      type: buffer.readInt32LE(offset + 8),
      body: buffer.subarray(offset + 12, offset + 4 + size - 2).toString('utf8'),
    });
    offset += 4 + size;
  }
  return { packets, rest: buffer.subarray(offset) };
}

class RconClient {
  constructor({ host, port, password }) {
    if (!password) throw new Error('RCON password missing. Run `openclaw factorio setup` or set FACTORIO_RCON_PASSWORD.');
    this.host = host;
    this.port = port;
    this.password = password;
    this.nextId = 1;
    this.pending = new Map();
    this.buffer = Buffer.alloc(0);
  }
  connect() {
    return new Promise((resolve, reject) => {
      this.socket = net.createConnection({ host: this.host, port: this.port });
      this.socket.on('data', chunk => this.onData(chunk));
      this.socket.once('error', reject);
      this.socket.once('connect', async () => {
        try {
          const auth = await this.request(SERVERDATA_AUTH, this.password);
          if (auth.id === -1) throw new Error('RCON authentication failed');
          resolve();
        } catch (error) { reject(error); }
      });
      this.socket.setTimeout(8000, () => reject(new Error('RCON connection timed out')));
    });
  }
  onData(chunk) {
    this.buffer = Buffer.concat([this.buffer, chunk]);
    const decoded = decodePackets(this.buffer);
    this.buffer = decoded.rest;
    for (const packet of decoded.packets) {
      const pending = this.pending.get(packet.id);
      if (pending) {
        this.pending.delete(packet.id);
        pending(packet);
      }
    }
  }
  request(type, body) {
    const id = this.nextId++;
    return new Promise((resolve, reject) => {
      const timer = setTimeout(() => {
        this.pending.delete(id);
        reject(new Error('RCON request timed out'));
      }, 8000);
      this.pending.set(id, packet => { clearTimeout(timer); resolve(packet); });
      this.socket.write(encodePacket(id, type, body));
    });
  }
  async command(command) {
    return (await this.request(SERVERDATA_EXECCOMMAND, command)).body;
  }
  close() { this.socket?.end(); }
}

function luaString(value) { return JSON.stringify(String(value ?? '')); }
function luaArg(value) {
  if (typeof value === 'number' && Number.isFinite(value)) return String(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (value == null) return 'nil';
  return luaString(value);
}
function remoteCall(api, args) {
  return `/c rcon.print(remote.call("openclaw", ${luaString(api)}${args.length ? ', ' + args.map(luaArg).join(', ') : ''}))`;
}
function maybeJson(output) {
  const trimmed = String(output || '').trim();
  const start = trimmed.indexOf('{');
  const end = trimmed.lastIndexOf('}');
  if (start !== -1 && end > start) {
    try { return JSON.stringify(JSON.parse(trimmed.slice(start, end + 1)), null, 2); } catch {}
  }
  return trimmed;
}

async function main() {
  const [cmd, ...args] = process.argv.slice(2);
  if (!cmd || cmd === '-h' || cmd === '--help' || cmd === 'help') return usage();
  let factorioCommand;
  switch (cmd) {
    case 'raw': factorioCommand = args.join(' '); break;
    case 'call': factorioCommand = remoteCall(args[0], args.slice(1).map(a => /^-?\d+(\.\d+)?$/.test(a) ? Number(a) : a)); break;
    case 'state': factorioCommand = remoteCall('state', [args[0] ?? '']); break;
    case 'inventory': factorioCommand = remoteCall('inventory', [args[0] ?? '']); break;
    case 'nearby': factorioCommand = remoteCall('nearby_entities', [args[0] ?? '', Number(args[1] ?? 10)]); break;
    case 'production': factorioCommand = remoteCall('production_stats', [args[0] ?? '']); break;
    case 'chat': factorioCommand = remoteCall('chat', [args.join(' ')]); break;
    default: throw new Error(`Unknown command: ${cmd}`);
  }
  const client = new RconClient(await loadConfig());
  await client.connect();
  try { console.log(maybeJson(await client.command(factorioCommand))); }
  finally { client.close(); }
}

main().catch(error => {
  console.error(`factorio-rcon: ${error.message}`);
  process.exit(1);
});
